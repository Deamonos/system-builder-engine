/**
 * ÉMOJIS NON RENDUS : selon la police système, certains caractères
 * sortent en « tofu » (le rectangle vide). Plutôt que d'entretenir à la
 * main une liste de ce qui passe chez qui, on MESURE : le caractère est
 * dessiné sur un canevas et comparé au tofu de référence. Ce qui ne
 * s'affiche pas ne s'affiche pas dans la grille non plus.
 *
 * Le test tourne UNE FOIS par session (résultat mémorisé) et ne coûte
 * rien : un canevas de 16 px, jamais ajouté au document.
 */
/* Mémoire PAR CARACTÈRE — surtout pas par liste : mettre en cache le
   résultat filtré ferait renvoyer la même grille à toutes les
   rubriques. Le canevas, lui, n'est créé qu'une fois. */
const _emojiSeen = new Map();
let _emojiCtx = null, _emojiRef = null;

/**
 * Drapeaux de PAYS : rendus par la police EMBARQUÉE du système.
 *
 * Ce ne sont pas des caractères mais des paires de lettres que la
 * police décide — ou non — de fusionner en image. Segoe UI Emoji ne le
 * fait pas : sous Windows, le navigateur affichait les deux lettres du
 * code (AC, AD, AE…). SBE embarque désormais le sous-ensemble « Noto
 * Color Emoji » correspondant (cf. la feuille de style), ils
 * s'affichent donc partout de la même façon.
 *
 * Cette fonction sert à les EXEMPTER du test de rectangle vide : ce
 * test mesure la police du SYSTÈME sur un canevas et ignore les
 * polices de la page — il les écarterait à tort.
 */
function isCountryFlag(em) {
  const cps = [...em].map(c => c.codePointAt(0));
  if (cps.length === 2 && cps.every(c => c >= 0x1F1E6 && c <= 0x1F1FF)) return true;
  /* Drapeaux de subdivision (Écosse, Pays de Galles…) : base + balises. */
  return cps[0] === 0x1F3F4 && cps.some(c => c >= 0xE0060 && c <= 0xE007F);
}
function supportedEmojis(list) {
  if (!_emojiCtx) {
    let ctx = null;
    try {
      const canvas = document.createElement("canvas");
      canvas.width = canvas.height = 20;
      ctx = canvas.getContext("2d", { willReadFrequently: true });
    } catch (_e) { /* environnement sans canevas */ }
    if (!ctx) return list;          /* pas de canevas : on n'écarte rien */
    ctx.font = "16px sans-serif";
    ctx.textBaseline = "top";
    _emojiCtx = ctx;
    const shot0 = (ch) => {
      ctx.clearRect(0, 0, 20, 20);
      ctx.fillText(ch, 0, 0);
      return ctx.getImageData(0, 0, 20, 20).data.join(",");
    };
    /* Références : un point de code inexistant, et le vide. */
    _emojiRef = { tofu: shot0("\u{10FFFF}"), blank: shot0(" ") };
  }
  const ctx = _emojiCtx;
  const shot = (ch) => {
    ctx.clearRect(0, 0, 20, 20);
    ctx.fillText(ch, 0, 0);
    return ctx.getImageData(0, 0, 20, 20).data.join(",");
  };
  return list.filter(([em]) => {
    /* Drapeaux : police embarquée, le test du canevas ne s'applique pas. */
    if (isCountryFlag(em)) return true;
    let ok = _emojiSeen.get(em);
    if (ok === undefined) {
      const px = shot(em);
      ok = px !== _emojiRef.tofu && px !== _emojiRef.blank;
      _emojiSeen.set(em, ok);
    }
    return ok;
  });
}


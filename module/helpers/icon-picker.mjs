/**
 * Dédoublonnage : les rubriques se recoupent (une même icône peut être
 * utile en « combat » et en « objets »). La PREMIÈRE occurrence gagne
 * et ABSORBE les mots-clés des suivantes — la recherche reste complète
 * sans que la grille affiche deux fois la même case.
 */
function dedupeIcons(list) {
  const index = new Map();
  for (const [val, kw] of list) {
    if (!index.has(val)) index.set(val, kw);
    else {
      const seen = new Set(index.get(val).split(/\s+/));
      const extra = kw.split(/\s+/).filter(w => w && !seen.has(w));
      if (extra.length) index.set(val, `${index.get(val)} ${extra.join(" ")}`);
    }
  }
  return [...index.entries()];
}

